#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
人形生物体型上限(巨人极限) 数值复核
只读, 不改 内容/。运行: python3 脚本/设计/设计_巨人极限.py

模型
  自相似放大 n 倍身高, 质量 ∝ n³
  骨骼: 股骨轴向压力 + 行走偏心弯矩, 人骨抗拉/抗压, 安全系数
  肌肉: 推重比 ∝ 1/n (肌力 ∝ L², 体重 ∝ L³)
  散热: 产热 ∝ M^0.75, 体表 ∝ M^(2/3), 单位面积热流 ∝ n^0.25
  供氧: 需氧 ∝ M^0.75, 肺泡面积 ∝ M^(2/3), 单位面积氧通量 ∝ n^0.25

行星参数(内容/地理/主行星.typ)
  g = 20 m/s², 海平面 1.013e5 Pa, He 76% / O2 20%, 平均摩尔质量 0.0106 kg/mol
  赤道海平面 300 K → 密度约 0.43 kg/m³, O2 分压约 20 kPa(与地球接近)
"""

import math

G = 20.0
G_E = 9.81
P0 = 1.013e5
MU = 0.0106
R_GAS = 8.314
T0 = 300.0
RHO_AIR = P0 * MU / (R_GAS * T0)
P_O2 = 0.20 * P0


def 标题(s):
    print()
    print("=" * 78)
    print(s)
    print("=" * 78)


def 股骨应力和上限(H0, M0, D0, d0, e_ratio, k_dyn, sig_t, sig_c, SF):
    """返回 (基准压侧应力 MPa, 基准拉侧应力 MPa, 骨骼允许放大倍数, 几何中间量)"""
    e0 = e_ratio * D0
    A = math.pi / 4 * (D0**2 - d0**2)
    W = math.pi * (D0**4 - d0**4) / (32 * D0)
    F = M0 * G * k_dyn
    轴压 = F / A
    弯曲 = F * e0 / W
    压侧 = (轴压 + 弯曲) / 1e6
    拉侧 = (弯曲 - 轴压) / 1e6
    n_c = (sig_c * 1e6 / SF) / (压侧 * 1e6)
    n_t = (sig_t * 1e6 / SF) / (拉侧 * 1e6)
    return 压侧, 拉侧, min(n_c, n_t), (A, W, F, e0)


def 主计算():
    标题("零、行星环境")
    print(f"  g = {G:.1f} m/s² (地球的 {G/G_E:.2f} 倍)")
    print(f"  海平面密度 = {RHO_AIR:.3f} kg/m³ (地球 1.225), O₂ 分压 = {P_O2/1e3:.1f} kPa")
    print(f"  氦为主: 分子扩散系数约为空气的 {math.sqrt(29/10.6):.2f} 倍, 导热系数约 6 倍")

    # ---------- 模板参数 ----------
    模板 = [
        # 名, H0, M0, 股骨外径, 内径, 推重比(地球), 肌肉/骨参数说明
        ("标准人形", 1.70, 68.0, 0.028, 0.016, 3.0),
        ("本设定人类", 2.00, 20.0, 0.033, 0.019, 2.0),
    ]
    SIG_T = 130.0      # 人骨抗拉 MPa
    SIG_C = 170.0      # 人骨抗压 MPa
    SF = 1.6
    K_DYN = 2.5        # 行走峰值载荷/静重
    E_RATIO = 0.5      # 偏心距/股骨外径
    需求_行走 = 1.2    # 行走单腿峰值/体重
    需求_站立 = 0.3    # 站立平衡所需肌力/体重
    Q_MAX = 450.0      # 裸体持续散热上限 W/m²(含汗蒸发, 氦环境)
    VO2_RATIO = 12.0   # 最大耗氧/静息耗氧

    结果 = []
    for 名, H0, M0, D0, d0, beta0 in 模板:
        标题(f"一、{名}: H₀={H0:.2f} m, M₀={M0:.1f} kg, g=20 m/s²")
        压, 拉, n_bone, geo = 股骨应力和上限(H0, M0, D0, d0, E_RATIO, K_DYN, SIG_T, SIG_C, SF)
        A, W, F, e0 = geo
        print(f"  股骨 Ø{D0*1000:.0f}×{(D0-d0)*1000/2:.1f} mm, 偏心 {e0*1000:.1f} mm, 行走载荷 {F/1e3:.2f} kN")
        print(f"  压侧 {压:.1f} MPa, 拉侧 {拉:.1f} MPa, 许用压 {SIG_C/SF:.0f} / 拉 {SIG_T/SF:.0f} MPa")
        print(f"  骨骼约束: n ≤ {n_bone:.2f}  →  身高 {H0*n_bone:.1f} m, 体重 {M0*n_bone**3:,.0f} kg")

        beta_eff = beta0 * G_E / G
        n_walk = beta_eff / 需求_行走
        n_stand = beta_eff / 需求_站立
        print(f"  地球推重比 {beta0:.1f} → 本行星 {beta_eff:.2f}")
        print(f"  肌肉约束(行走): n ≤ {n_walk:.2f}  →  身高 {H0*n_walk:.2f} m, 体重 {M0*n_walk**3:.1f} kg")
        print(f"  肌肉约束(仅站立): n ≤ {n_stand:.2f}  →  身高 {H0*n_stand:.2f} m, 体重 {M0*n_stand**3:.0f} kg")

        A0 = 0.108 * M0 ** (2 / 3)
        q0 = 1.0 * M0 / A0
        n_heat = (Q_MAX / q0) ** 4
        n_oxy = VO2_RATIO ** 4
        print(f"  散热: 静息 {q0:.1f} W/m², 上限 {Q_MAX:.0f} W/m² → n ≤ {n_heat:,.0f} "
              f"(身高 {H0*n_heat:,.0f} m) 不构成限制")
        print(f"  供氧: 最大/静息 {VO2_RATIO:.0f} 倍 → n ≤ {n_oxy:,.0f} "
              f"(身高 {H0*n_oxy:,.0f} m) 不构成限制")

        结果.append((名, H0, M0, n_bone, n_walk, n_stand))
        # 分档结论
        档 = [
            ("奔跑/跳跃", beta_eff / 2.5),
            ("持续行走", n_walk),
            ("缓慢移动", beta_eff / 1.0),
            ("仅站立", min(n_stand, n_bone)),
        ]
        标题(f"二、{名}: 分档上限")
        print(f"  {'功能':<10}{'n':>7}{'身高 m':>10}{'体重 kg':>12}  瓶颈")
        for 功能, n in 档:
            n = min(n, n_bone)
            瓶颈 = "骨骼" if n >= n_bone - 1e-9 else "肌肉"
            print(f"  {功能:<10}{n:>7.2f}{H0*n:>10.2f}{M0*n**3:>12.1f}  {瓶颈}")

    # ---------- 敏感性 ----------
    标题("三、骨骼上限的敏感性(标准人形)")
    H0, M0, D0, d0 = 1.70, 68.0, 0.028, 0.016
    print(f"  {'安全系数':>8}{'动态系数':>10}{'n':>8}{'身高 m':>10}")
    for sf in (1.4, 1.6, 2.0):
        for k in (1.5, 2.5, 3.5):
            _, _, n, _ = 股骨应力和上限(H0, M0, D0, d0, E_RATIO, k, SIG_T, SIG_C, sf)
            print(f"  {sf:>8.1f}{k:>10.1f}{n:>8.2f}{H0*n:>10.2f}")

    标题("四、肌肉上限的敏感性(标准人形, 持续行走)")
    print(f"  {'推重比':>8}{'n':>8}{'身高 m':>10}")
    for b in (2.0, 3.0, 4.0):
        n = b * G_E / G / 需求_行走
        print(f"  {b:>8.1f}{n:>8.2f}{H0*n:>10.2f}")

    # ---------- 结论 ----------
    标题("五、结论")
    print("  1. 20 m/s² 下, 人形自相似放大首先被肌肉卡住: 肌力 ∝ L², 体重 ∝ L³,")
    print("     推重比 ∝ 1/n. 标准人形能持续行走的上限约 n=1.2, 即 2.1 m / 99 kg.")
    print("  2. 只要求站立(骨骼承重, 肌肉仅平衡), 骨骼上限 n≈3.2, 即 5.5 m / 2.3 t.")
    print("  3. 本设定人类体重仅 20 kg, 骨骼可撑到 30 m 量级; 但设定写明肌肉营养不良,")
    print("     推重比低, 其行走能力在 2 m 已经到顶, 放大后立刻失去行走能力.")
    print("  4. 散热与供氧在数十米以内都不构成限制: 氦大气氧分压 20 kPa 接近地球,")
    print("     导热好, 且代谢 ∝ M^0.75、体表 ∝ M^(2/3), 单位面积热流只 ∝ n^0.25.")
    print("  5. 想做出更大的巨人, 只能改这三项之一: 提高肌肉推重比(改造肌纤维),")
    print("     降低体重标度(低密度组织, 本设定人类正是此路), 或改成四足/多支撑.")
    print(f"  6. 若三项同时改造, 骨骼上限可推到 n≈{结果[0][3]:.1f}; 散热按 Q_MAX=450 W/m²")
    print("     仍允许上百米, 届时真正的瓶颈转为循环系统的流体静压与神经传导.")


if __name__ == "__main__":
    主计算()
