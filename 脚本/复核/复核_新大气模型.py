import math

g = 20.0
R = 8.314462618
P0 = 1.013e5
等温温 = 216.65
平流层顶温 = 232.65
中间层降率 = 2.5e-3

# (名, 质量 kg/mol, 自由度 f(=cp*M/R), 海平面体积比)
物种 = [
    ("He",  0.004003, 5, 0.76),
    ("O2",  0.032000, 7, 0.20),
    ("N2",  0.028013, 7, 0.019),
    ("CO2", 0.044010, 7, 0.010),
    ("H2O", 0.018015, 8, 0.010),
]
N = len(物种)

赤道参数 = dict(海平面温=300.0, 等温顶=17.2e3, 平流层顶=24.0e3, 升率=2.3529e-3)
极点参数 = dict(海平面温=240.0, 等温顶=8.0e3, 平流层顶=22.4e3, 升率=1.1111e-3)

def 体积比(E):
    w = [物种[i][3] * math.exp(-E[i]) for i in range(N)]
    s = sum(w)
    return [v/s for v in w]

def 定压比热(比):
    m = [比[i]*物种[i][1] for i in range(N)]
    tot = sum(m)
    return sum(m[i]/tot * (物种[i][2]/2) * R / 物种[i][1] for i in range(N))

def 平均摩尔质量(比):
    return sum(比[i]*物种[i][1] for i in range(N))

步长 = 5.0
def 对流层积分(区, h):
    n = math.ceil(h/步长)
    if n <= 0:
        return 区["海平面温"], [0.0]*N
    dh = h/n
    T = 区["海平面温"]; E = [0.0]*N
    for _ in range(n):
        cp = 定压比热(体积比(E))
        Tn = T - g/cp*dh
        Tm = 0.5*(T+Tn)
        E = [E[i] + 物种[i][1]*g/(R*Tm)*dh for i in range(N)]
        T = Tn
    return T, E

def 求对流层顶(区):
    T = 区["海平面温"]; E = [0.0]*N; h = 0.0
    for _ in range(4000):
        cp = 定压比热(体积比(E))
        Tn = T - g/cp*步长
        Tm = 0.5*(T+Tn)
        E = [E[i] + 物种[i][1]*g/(R*Tm)*步长 for i in range(N)]
        T = Tn; h += 步长
        if T <= 等温温:
            break
    return h, 对流层积分(区, h)[1]

def 大气温度(区, 顶, h):
    if h <= 顶["h"]:
        return 对流层积分(区, h)[0]
    if h <= 区["等温顶"]:
        return 等温温
    if h <= 区["平流层顶"]:
        return 等温温 + 区["升率"]*(h-区["等温顶"])
    return 平流层顶温 - 中间层降率*(h-区["平流层顶"])

def 扩散积分(区, 顶, h):
    积 = 0.0
    上 = min(h, 区["等温顶"])
    if 上 > 顶["h"]:
        积 += g/R*(上-顶["h"])/等温温
    if h > 区["等温顶"]:
        T2 = 等温温 + 区["升率"]*(min(h, 区["平流层顶"])-区["等温顶"])
        积 += g/(R*区["升率"])*math.log(T2/等温温)
    if h > 区["平流层顶"]:
        T3 = 平流层顶温 - 中间层降率*(h-区["平流层顶"])
        积 += g/(R*中间层降率)*math.log(平流层顶温/T3)
    return 积

def 扩散指数(区, 顶, h):
    if h <= 顶["h"]:
        return 对流层积分(区, h)[1]
    Ψ = 扩散积分(区, 顶, h)
    return [顶["E"][i] + 物种[i][1]*Ψ for i in range(N)]

def 组分比(区, 顶, h):
    return 体积比(扩散指数(区, 顶, h))

def 大气密度(区, 顶, h):
    E = 扩散指数(区, 顶, h)
    比 = 体积比(E)
    P = sum(物种[i][3]*P0*math.exp(-E[i]) for i in range(N))
    return P*平均摩尔质量(比)/(R*大气温度(区, 顶, h))

def 大气声速(区, 顶, h):
    比 = 组分比(区, 顶, h)
    Mb = 平均摩尔质量(比)
    cp = 定压比热(比)
    γ = cp/(cp - R/Mb)
    return math.sqrt(γ*R*大气温度(区, 顶, h)/Mb)

# 区域常量
def 建区(区):
    h, E = 求对流层顶(区)
    return dict(**区, h=h, E=E)

赤道顶 = 建区(赤道参数)
极点顶 = 建区(极点参数)

print("="*78)
print("一、成分与比热/递减率")
print("="*78)
比0 = 体积比([0.0]*N)
Mb0 = 平均摩尔质量(比0)
cp0 = 定压比热(比0)
print(f"  海平面 M̄ = {Mb0:.5f} kg/mol = {Mb0*1000:.2f} g/mol")
print(f"  海平面 c_p = {cp0:.1f} J/(kg·K)")
print(f"  海平面 Γ = g/c_p = {g/cp0*1000:.2f} K/km")
# 各成分质量分数与 c_p,i
print("  各成分 c_p,i = (f/2)R/M:")
for i in range(N):
    print(f"    {物种[i][0]:4s} f={物种[i][2]}  c_p={物种[i][2]/2*R/物种[i][1]:7.1f} J/(kg·K)  质量分数={比0[i]*物种[i][1]/Mb0:.3f}")
# 对流层顶处的 c_p
for 名, 顶 in (("赤道", 赤道顶), ("极点", 极点顶)):
    比t = 体积比(顶["E"])
    print(f"  {名}对流层顶: c_p={定压比热(比t):.1f}, Γ={g/定压比热(比t)*1000:.2f} K/km")

print()
print("="*78)
print("二、对流层顶")
print("="*78)
for 名, 顶 in (("赤道", 赤道顶), ("极点", 极点顶)):
    print(f"  {名}: 海平面 {顶['海平面温']:.0f} K → 对流层顶 h={顶['h']/1000:.2f} km, T={大气温度((赤道参数 if 名=='赤道' else 极点参数), 顶, 顶['h']):.1f} K")

print()
print("="*78)
print("三、温度/密度/声速/组分剖面")
print("="*78)
for 名, 区, 顶 in (("赤道", 赤道参数, 赤道顶), ("极点", 极点参数, 极点顶)):
    print(f"\n  [{名}]  (对流层顶 {顶['h']/1000:.2f} km)")
    print(f"  {'h km':>6} {'T K':>7} {'ρ kg/m³':>10} {'a m/s':>7} {'He%':>6} {'O₂%':>6} {'N₂%':>6}")
    比 = None
    for hkm in (0, 1, 2, 3, 5, 8.5, 10, 12, 15, 17, 20, 24, 30, 35, 40, 45, 50, 55, 60):
        h = hkm*1000
        T = 大气温度(区, 顶, h)
        ρ = 大气密度(区, 顶, h)
        a = 大气声速(区, 顶, h)
        b = 组分比(区, 顶, h)
        print(f"  {hkm:6.1f} {T:7.1f} {ρ:10.3e} {a:7.1f} {b[0]*100:6.1f} {b[1]*100:6.1f} {b[2]*100:6.1f}")

print()
print("="*78)
print("四、关键高度点(赤道)")
print("="*78)
区, 顶 = 赤道参数, 赤道顶
for hkm in (15, 20, 24, 40, 60):
    h = hkm*1000
    b = 组分比(区, 顶, h)
    print(f"  {hkm:3.0f} km: T={大气温度(区,顶,h):.1f} K, ρ={大气密度(区,顶,h):.3e} kg/m³, "
          f"a={大气声速(区,顶,h):.1f} m/s, He={b[0]*100:.1f}%, O₂={b[1]*100:.1f}%")

print()
print("="*78)
print("五、层界处温度与递减率")
print("="*78)
for 名, 区, 顶 in (("赤道", 赤道参数, 赤道顶), ("极点", 极点参数, 极点顶)):
    print(f"  [{名}] 对流层顶 {顶['h']/1000:.2f} km / 等温顶 {区['等温顶']/1000:.1f} km / 平流层顶 {区['平流层顶']/1000:.1f} km")
    print(f"        平流层升温率 {区['升率']*1000:.4f} K/km, 至 {平流层顶温} K")
    print(f"        中间层 -{中间层降率*1000:.1f} K/km")

print()
