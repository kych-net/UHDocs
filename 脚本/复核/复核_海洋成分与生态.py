"""复核: 海洋不同成分/参数对"非水分层"与"生态"的影响

行星参数(见 内容/地理/主行星.typ, 内容/怪物/怪动植物.typ):
  g = 20 m/s^2, 海平面气压 P0 = 1.013e5 Pa
  大气富氧: He 76% / O2 20% / N2 1.9% / CO2 1% / NH3 0.1%
  生态依赖: 侧线感知流体; 游泳(25 m/s); 鳃; 体温42C(315K);
            植物世代用 Fe/S/H2 化学能; 已有"深海热泉过热水"设定

两条影响路径:
  路径A(物理): 成分改变海水密度 -> 改变"非水液体能否沉底"的温度/盐度门槛
  路径B(化学): 成分提供/消耗非水层物质与化学能 -> 直接改变生态
"""

import math

g = 20.0
P0 = 1.013e5
R = 8.314
kappa = 4.5e-10


def rho_sw(T, S, h):
    """海水密度: 温盐表层密度 + 静水压压缩"""
    rho0 = 1000.0 + 0.78 * S - 0.15 * (T - 277.0)
    return rho0 * (1 + kappa * rho0 * g * h)


# 液态 CO2 饱和密度(文献值)
co2_T = [216.6, 240.0, 250.0, 260.0, 273.0, 283.0, 293.0, 304.1]
co2_rho = [1178.0, 1085.0, 1040.0, 990.0, 928.0, 850.0, 773.0, 468.0]


def co2_density(T):
    if T <= co2_T[0] or T >= co2_T[-1]:
        return None
    for i in range(len(co2_T) - 1):
        if co2_T[i] <= T <= co2_T[i + 1]:
            f = (T - co2_T[i]) / (co2_T[i + 1] - co2_T[i])
            return co2_rho[i] + f * (co2_rho[i + 1] - co2_rho[i])
    return None


def co2_sink_threshold(S, h):
    """求液态CO2密度恰等于海水的温度(低于此温度才沉底)"""
    for T10 in range(3040, 2165, -1):
        T = T10 / 10.0
        d = co2_density(T)
        if d is not None and d >= rho_sw(T, S, h):
            return T
    return None


print("=" * 80)
print("路径A: 盐度/深度 对 液态CO2沉底阈值温度 的影响")
print("=" * 80)
print("  盐度psu   深度    海水密度(250K)   液态CO2沉底阈值T")
for S in (0, 35, 70, 120):
    for h in (1000, 4000):
        Tstar = co2_sink_threshold(S, h)
        print(f"  {S:5.0f}   {h:5d}m    {rho_sw(250, S, h):8.1f}       {Tstar:.0f} K")
print("  => 盐度越高、海水越重, CO2沉底门槛温度越低(更难形成非水分层)")

print()
print("=" * 80)
print("路径A: 盐度 对 渗透压 的影响 (生态: 渗透调节负担)")
print("=" * 80)
print("  盐度psu   渗透压(300K)")
for S in (0, 35, 70, 120):
    m = S / 58.44 * 1000.0   # mol/m^3 (按NaCl)
    pi = 2 * m * R * 300.0   # 范特霍夫 i=2
    print(f"  {S:5.0f}    {pi/1e6:6.2f} MPa")
print("  => 盐度线性抬高渗透压, 直接增加皮肤/鳃的调节负担")

print()
print("=" * 80)
print("路径A: 溶解O2 (生态: 好氧容量)")
print("=" * 80)
# Henry: c = k(T) * P_O2; k(298K)≈1.3e-3 mol/(L·atm); 盐析按 Setchenow
def o2_solubility(T, S):
    k298 = 1.3e-3
    dH = 1700.0 * (1.0 / T - 1.0 / 298.0)   # 溶解度随温度略降
    kT = k298 * math.exp(dH)
    ks = 10 ** (-0.0032 * S)                 # Setchenow 盐析
    return kT * 0.2 * ks                     # 行星 O2 分压 = 0.2 atm

print("  温度K  盐度psu   溶解O2 (mg/L)")
for T in (300, 280, 260, 240):
    for S in (0, 35, 70):
        c = o2_solubility(T, S) * 32000.0    # mol/L -> mg/L
        print(f"  {T:5.0f}   {S:5.0f}     {c:6.1f}")
print("  => 冷水+低盐溶氧最高; 强分层水体底部仍会缺氧(交换受限)")

print()
print("=" * 80)
print("路径B: 溶解成分 -> 可形成的非水层 与 化学能生态位")
print("=" * 80)
成分 = [
    ("高溶解CO2/碳酸盐", "液态CO2层(T<~250K)", "酸化(pH低), 供化能固碳; 抑制钙质生物"),
    ("高硫酸盐/硫化物", "液态硫(热泉口局部, T>388K)", "H2S/Fe2+ 化能生态繁荣(对应植物世代)"),
    ("高溴", "液溴层(密度3.1, 需Br富集)", "强氧化毒性, 局部灭菌; 需特殊来源"),
    ("高铁/还原性", "不直接成层", "Fe2+ 化学能, 对应'铁还原细菌'生态位"),
    ("高溶解O2", "不直接成层(氧化剂)", "好氧生态繁荣, 但氧化掉还原性非水层物质"),
]
for 成分名, 非水层, 生态 in 成分:
    print(f"  {成分名:16s} -> 非水层: {非水层:24s} 生态: {生态}")

print()
print("== 结论 ==")
print("  1) 物理路径: 盐度是'非水分层'的抑制剂——盐度升高使海水更重, CO2沉底门槛温度下降(35->120psu约降10K以上)。")
print("  2) 化学路径: 成分决定'有哪些非水液体可用'——CO2层、液态硫、液溴各有成分前提;")
print("     而富氧海水会氧化还原性物质(H2S/CH4/NH3), 所以稳定的非水层多为氧化产物(CO2、硫)。")
print("  3) 生态路径: 溶氧、渗透压、化学能底物三者由成分决定; 分层越强(高盐/低温)垂向交换越弱, 底部越缺氧,")
print("     但高铁高硫的成分(热泉活跃)恰好支撑化能生态, 与设定中植物世代的 Fe/S/H2 利用一致。")