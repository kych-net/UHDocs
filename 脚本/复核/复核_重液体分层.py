"""复核: 深海能否用 CCl4 或其它不溶于水的重液体分层

行星参数: g = 20 m/s^2, 富氧(He76/O2 20), 海面 赤道300K / 极点240K
深海温度取: 热带 280K, 寒带 240K (设定未定义, 作情景假设)

判据(四者同时满足):
  (1) 液态: 海底温度在熔点与沸点之间
  (2) 密度: 液体密度 > 海水密度
  (3) 不互溶: 水中溶解度低, 析出独立相
  (4) 稳定: 深海无光厌氧下不易分解
"""

g = 20.0


def rho_sw(T, S, h):
    rho0 = 1000.0 + 0.78 * S - 0.15 * (T - 277.0)
    return rho0 * (1 + 4.5e-10 * rho0 * g * h)


# (名, 密度 g/cm^3@293K, 熔点K, 沸点K, 水中溶解度, 稳定性, 密度温度系数 /K)
候选 = [
    ("CCl4", 1.594, 250.2, 349.9, "0.8 g/L", "惰性, 仅光解", 0.0020),
    ("CHCl3", 1.489, 209.7, 334.3, "8 g/L", "较惰性, 光解", 0.0018),
    ("CS2", 1.263, 161.6, 319.4, "微溶 2 g/L", "易水解/氧化", 0.0013),
    ("CH2Br2", 2.477, 221.0, 370.0, "微溶", "较稳定", 0.0016),
    ("CHBr3", 2.890, 281.0, 422.0, "微溶", "光解", 0.0017),
    ("全氟萘烷", 1.940, 263.0, 415.0, "极不溶", "极稳定", 0.0016),
]


def rho_liquid(rho293, alpha, T):
    return rho293 * (1 - alpha * (T - 293.0))


print("=" * 88)
print("候选不溶水重液体物性 (密度@293K)")
print("=" * 88)
print("  物质        密度g/cm3   熔点K   沸点K   水中溶解度    稳定性")
for 名, r, Tm, Tb, sol, st, a in 候选:
    print(f"  {名:9s}  {r:6.3f}   {Tm:6.1f}  {Tb:6.1f}   {sol:10s}  {st}")

print()
print("=" * 88)
print("深海分层判据 (海水密度: 热带280K/4000m ≈ %.0f, 寒带240K/4000m ≈ %.0f kg/m^3)"
      % (rho_sw(280, 35, 4000), rho_sw(240, 35, 4000)))
print("=" * 88)
for 名, r, Tm, Tb, sol, st, a in 候选:
    line = f"  {名:9s}"
    for 区, T in (("热带280K", 280.0), ("寒带240K", 240.0)):
        rs = rho_sw(T, 35, 4000)
        if T < Tm:
            res = "固态"
        elif T > Tb:
            res = "气态"
        else:
            rl = rho_liquid(r, a, T) * 1000
            res = f"液态 比{rl/rs:.2f} {'沉底' if rl > rs else '上浮'}"
        line += f" | {区}: {res:20s}"
    print(line)

print()
print("=" * 88)
print("来源: 自然卤代有机物 (海洋生物卤代酶合成)")
print("=" * 88)
print("  - 海洋生物(藻类/微生物)可经卤过氧化物酶合成 CHBr3/CHBr2Cl/CH2Br2 等")
print("  - 行星富氧且海水含 Br-, 卤代酶路径有原料(卤素)与氧化剂(H2O2)")
print("  - CCl4 自然来源稀少(多为火山/工业), 若采用需设定生物合成路径")
print("  - CHBr3 密度2.89 最高, 但熔点281K 需更暖海域")

print()
print("=" * 88)
print("稳定性: 深海环境反而有利")
print("=" * 88)
print("  - 光解需 UV, 深海无光 -> 卤代烃光解被抑制")
print("  - 厌氧 -> 还原性脱卤受抑; CCl4 本身化学惰性")
print("  - 富氧海水可能缓慢氧化还原性物质(CS2), 但对 CCl4/全氟物几乎无作用")

print()
print("== 结论 ==")
print("  1) CCl4 在深海完全满足前三条: 熔点250.2K(热带280K为液态), 密度1.59(约海水1.5倍), 水中溶解度仅0.8 g/L -> 沉底成清晰两相。")
print("  2) 温度窗口: CCl4 需 T > 250.2K, 只适用暖海(热带); 寒带240K 下凝固。")
print("     寒带可改用低熔点卤代物: CHCl3(209.7K)/CH2Br2(221K)/CS2(161.6K)。")
print("  3) 稳定性最佳的是 CCl4 与全氟萘烷: 深海无光厌氧, 几乎不分解;")
print("     全氟萘烷密度1.94且极不溶, 但熔点263K, 同样偏暖。")
print("  4) 主要瓶颈仍是来源: 需设定海洋生物卤代酶合成路径;")
print("     自然海洋卤代烃以含溴物(CHBr3/CH2Br2)为主, 含氯的CCl4需额外来源。")
print("  5) 生态: 卤代烃层是麻醉/肝毒性的溶剂带, 比液溴温和, 可支持耐溶剂极端微生物。")