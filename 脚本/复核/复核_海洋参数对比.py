"""复核: 不同海洋参数对"分层结构"与"生态"的影响

行星参数(见 内容/地理/主行星.typ, 内容/怪物/怪动植物.typ):
  g = 20 m/s^2, 海平面气压 1.013e5 Pa
  海面温度: 赤道 300K, 极点 240K
  大气富氧(He 76% / O2 20%), CO2 仅 1%
  生态侧依赖(见 内容/怪物/怪动植物.typ):
    - 侧线与鱼类同源, 感知流体运动 -> 对分层界面/流场敏感
    - 嗜血仙子可游泳(25 m/s), 有鳃丝推进
    - 体温恒定 42°C(315K), 有主动制冷/保温
    - 植物世代靠 Fe/S/H2 化学能、光能 -> 依赖热泉与透光深度
    - 已有"深海热泉过热水"过热级设定

对比四组海洋参数(深度 h / 海底温度 Tb / 盐度 S):
"""

g = 20.0
P0 = 1.013e5
kappa = 4.5e-10   # 海水压缩系数 /Pa


def rho_sw(T, S, h):
    """海水密度: 表层密度随温盐变化, 再按静水压压缩"""
    rho0 = 1000.0 + 0.78 * S - 0.15 * (T - 277.0)
    dP = rho0 * g * h
    return rho0 * (1 + kappa * dP)


def P_at(h):
    return P0 + 1028.0 * g * h


# 液态 CO2 饱和密度(文献值)
co2_T = [216.6, 240.0, 250.0, 260.0, 273.0, 283.0, 293.0, 304.1]
co2_rho = [1178.0, 1085.0, 1040.0, 990.0, 928.0, 850.0, 773.0, 468.0]


def co2_density(T):
    if T <= co2_T[0] or T >= co2_T[-1]:
        return None
    for i in range(len(co2_T) - 1):
        if co2_T[i] <= T <= co2_T[i + 1]:
            f = (T - co2_T[i]) / (co2_T[i + 1] - co2_T[i])
            return co2_rho[i] + f * (co2_rho[i + 1] - co2_rho[i])
    return None


# 情景: (名, 深度 m, 海底温度 K, 盐度 psu)
情景 = [
    ("A 浅海暖水", 500, 285.0, 35.0),
    ("B 深海冷水", 4000, 275.0, 35.0),
    ("C 极地冷海", 2000, 240.0, 35.0),
    ("D 高盐深盆", 4000, 255.0, 80.0),
]

print("=" * 78)
print("情景          深度    底压      海底海水密度   温盐表层密度   垂向密度差")
print("=" * 78)
for 名, h, Tb, S in 情景:
    rho_b = rho_sw(Tb, S, h)
    rho_surf = rho_sw(300.0 if "浅" in 名 or "深" in 名 else 240.0, S, 0)
    print(f"{名:12s} {h:5d}m  {P_at(h)/1e6:5.1f}MPa  {rho_b:8.1f}     {rho_surf:8.1f}     {rho_b-rho_surf:6.1f}")

print()
print("=" * 78)
print("情景          液态CO2密度@Tb   CO2能否沉底   液化所需深度   CO2层")
print("=" * 78)
for 名, h, Tb, S in 情景:
    rho_b = rho_sw(Tb, S, h)
    d_co2 = co2_density(Tb)
    if d_co2 is None:
        verdict, txt = "无(超临界/气)", "不形成"
    elif d_co2 > rho_b:
        verdict, txt = "能", "可形成"
    else:
        verdict, txt = "否(上浮)", "不形成"
    # 液化所需最小深度: 取 Tb 对应饱和蒸气压粗估
    Psat = {240.0: 1.0e6, 255.0: 2.3e6, 275.0: 3.7e6, 285.0: 4.6e6}.get(Tb, 3.0e6)
    h_min = (Psat - P0) / (1028.0 * g)
    液化 = f"{h_min:.0f}m" if h > h_min else f"不足({h_min:.0f}m)"
    d_txt = f"{d_co2:.0f}" if d_co2 else "--"
    print(f"{名:12s} {d_txt:>10s}       {verdict:8s}   {液化:12s}  {txt}")

print()
print("=" * 78)
print("生态影响对比")
print("=" * 78)
生态 = {
    "A 浅海暖水": "全海透光, 光合世代繁盛; 垂向混合强, 分层弱; 底层暖(285K)接近体温, 温控负担小; 无CO2层",
    "B 深海冷水": "无光深部靠热泉化学能(Fe/S/H2); 温跃层稳定但底温275K仍>248K, CO2不沉底; 高压(82MPa)考验耐压",
    "C 极地冷海": "底温240K, 液态CO2可沉底形成'CO2湖'; 局部强酸性缺氧成死亡带, 但可支撑化能微生物; 冷水需保温",
    "D 高盐深盆": "盐度高->海水密度大, CO2更难沉底; 盐跃层主导, 垂向交换最弱, 深层易缺氧; 渗透压考验皮肤/鳃",
}
for 名, _, _, _ in 情景:
    print(f"  {名}: {生态[名]}")

print()
print("== 结论 ==")
print("  分层结构由'海底温度'与'盐度'两个参数主导:")
print("  - 海底温度 < ~248K 才有液态CO2沉底(C); 否则只有常规温盐分层(A/B/D)")
print("  - 盐度升高使海水更重, 既强化盐跃层(D), 也抬高CO2沉底门槛")
print("  生态上, 分层越强(盐跃层/CO2层)垂向混合越弱, 深层越缺氧;")
print("  但冷海(C)的CO2层可提供新的化能生态位, 与热泉生态位叠加。")