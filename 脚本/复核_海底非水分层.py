"""复核: 海底能否形成"非水分层"(沉底的非水液体层)

行星参数(见 内容/地理/主行星.typ, 内容/怪物/怪动植物.typ):
  g = 20 m/s^2 (地球约 2 倍)
  海平面气压 P0 = 1.013e5 Pa
  海面温度: 赤道 300K, 极点 240K
  大气: He 76% / O2 20% / N2 1.9% / CO2 1% / H2O 1% / NH3 0.1%  -> 富氧
  海洋参数(深度/盐度/温度)在设定中未给出, 此处按类地球海水(盐度 35)近似

判据(四者需同时满足才可能形成稳定分层):
  (1) 液态   : 该物质在海底温压下为液态
  (2) 密度   : 液体密度 > 海水密度, 否则上浮
  (3) 不互溶 : 与水不互溶, 否则被湍流混合稀释
  (4) 稳定   : 不被富氧海水氧化或水解
"""

g = 20.0
P0 = 1.013e5
rho_sw0 = 1028.0    # 表层海水密度 kg/m^3 (盐度 35, 类地球)
kappa = 4.5e-10     # 海水压缩系数 /Pa


def P(h):
    return P0 + rho_sw0 * g * h


def rho_sw(h):
    return rho_sw0 * (1 + kappa * (P(h) - P0))


print("== 压力与海水密度随深度 (g = 20 m/s^2) ==")
for h in (0, 100, 200, 370, 500, 1000, 2000, 4000):
    print(f"  深度 {h:5d} m : P = {P(h)/1e6:6.2f} MPa, 海水密度 = {rho_sw(h):7.1f} kg/m^3")

# --- 液态 CO2 饱和密度随温度(文献值, kg/m^3) ---
co2_T = [216.6, 240.0, 250.0, 260.0, 273.0, 283.0, 293.0, 304.1]
co2_rho = [1178.0, 1085.0, 1040.0, 990.0, 928.0, 850.0, 773.0, 468.0]


def co2_density(T):
    if T <= co2_T[0] or T >= co2_T[-1]:
        return None
    for i in range(len(co2_T) - 1):
        if co2_T[i] <= T <= co2_T[i + 1]:
            f = (T - co2_T[i]) / (co2_T[i + 1] - co2_T[i])
            return co2_rho[i] + f * (co2_rho[i + 1] - co2_rho[i])
    return None


# --- 候选非水液体 ---
# (名, 熔点K, 沸点K, 液态密度 kg/m^3 及其温度, 与水互溶性, 氧化性大气下的稳定性)
候选 = [
    ("液态CO2", 216.6, 194.7 + 0, None, "中等溶解(成碳酸)", "稳定(本身是氧化产物)"),
    ("液态硫S", 388.4, 717.8, (1810, 400), "不溶", "稳定"),
    ("液溴Br2", 265.8, 332.0, (3100, 293), "微溶(3.4g/100mL)", "稳定(本身是氧化剂)"),
    ("CS2", 161.6, 319.4, (1263, 293), "微溶", "易水解/氧化"),
    ("液态SO2", 197.7, 263.1, (1434, 273), "极易溶(成亚硫酸)", "被O2氧化成SO3"),
    ("液态H2S", 190.6, 212.8, (914, 213), "微溶", "被O2氧化成S/SO2"),
    ("液氨NH3", 195.4, 239.8, (682, 240), "互溶", "被氧化"),
    ("液态CH4", 90.7, 111.7, (422, 112), "微溶", "被氧化"),
]

print("\n== 候选非水液体: 密度对比 ==")
print(f"  参考: 海水密度约 {rho_sw(1000):.0f} ~ {rho_sw(4000):.0f} kg/m^3 (1000~4000 m)")
print("  物质        液态密度      能否沉底(密度>海水)?   互溶/稳定")
for 名, Tm, Tb, dens, 溶, 稳 in 候选:
    if 名 == "液态CO2":
        print(f"  {名:9s} 216.6~304K 间 468~1178(随温变)  见下方阈值计算         {溶} / {稳}")
    else:
        r, T = dens
        ok = "是" if r > rho_sw(4000) else ("临界" if r > rho_sw(0) else "否")
        print(f"  {名:9s} {r:5.0f} @ {T}K                {ok:>4s}                 {溶} / {稳}")

# --- 液态 CO2 沉底阈值: 密度等于海水时的温度 ---
print("\n== 液态CO2沉底条件 ==")
rho_target = rho_sw(2000)
T_crit_density = None
for T10 in range(2170, 3040, 5):
    T = T10 / 10.0
    d = co2_density(T)
    if d is not None and d <= rho_target:
        T_crit_density = T
        break
print(f"  海水在 2000 m 处密度约 {rho_target:.0f} kg/m^3")
print(f"  液态CO2密度等于该值约在 T = {T_crit_density:.1f} K")
print(f"  => 海底温度须低于约 {T_crit_density:.0f} K, 液态CO2才会沉底(否则上浮)")

# CO2 液化所需最小深度: 饱和蒸气压 > 静水压
# 250K 饱和蒸气压约 1.8 MPa, 240K 约 1.0 MPa
for T, Psat in ((240.0, 1.0e6), (250.0, 1.8e6), (273.0, 3.5e6)):
    h_min = (Psat - P0) / (rho_sw0 * g)
    print(f"  T = {T:.0f} K: CO2饱和蒸气压约 {Psat/1e6:.1f} MPa -> 需深度 > {h_min:.0f} m 才液化")

print("\n== 结论 ==")
print("  1) 还原性液体(CH4/NH3/H2S/SO2)在富氧海水下不成立: 密度多小于海水(上浮), 且被氧化或与水互溶。")
print("  2) 唯一密度足够又稳定的候选是液态CO2、液态硫、液溴。")
print("  3) 液态CO2: 需海底温度低于约 250 K 才会沉底; 高纬海域(海面240K)可能满足, 赤道(海面300K)基本不满足。")
print("  4) 液态硫: 需局部 > 388 K, 只在热泉口附近短暂存在, 不能形成大范围稳定分层。")
print("  5) 液溴: 密度与稳定性都满足, 但行星设定中无溴的富集来源。")