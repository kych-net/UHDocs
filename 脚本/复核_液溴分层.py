"""复核: 液溴(Br2)在海底形成分层的可行性

行星参数(见 内容/地理/主行星.typ):
  g = 20 m/s^2, 海平面气压 1.013e5 Pa
  大气富氧: O2 20% -> O2/H2O 电对 E°=1.23V, 可氧化 Br- 为 Br2
  海面温度: 赤道 300K, 极点 240K

判据:
  (1) 物态: 液溴在海底温度下是否为液态 (熔点 265.8K, 沸点 332.0K)
  (2) 密度: 液溴密度 > 海水密度 (否则上浮)
  (3) 互溶: 液溴微溶于水, 超过饱和即析出成独立相
  (4) 来源: 海水 Br- 能否富集到形成可观厚度的液溴层
"""

import math

g = 20.0
P0 = 1.013e5
kappa = 4.5e-10

T_melt = 265.8   # Br2 熔点 K
T_boil = 332.0   # Br2 沸点 K


def rho_Br2(T):
    """液态溴密度 kg/m^3 (线性近似, 293K 取 3102)"""
    return (3.102 - 0.0043 * (T - 293.0)) * 1000.0


def rho_sw(T, S, h):
    rho0 = 1000.0 + 0.78 * S - 0.15 * (T - 277.0)
    return rho0 * (1 + kappa * rho0 * g * h)


print("=" * 74)
print("1) 液溴物态随温度 (熔点 265.8K, 沸点 332.0K)")
print("=" * 74)
for T in (240, 250, 265.8, 273, 293, 300, 315, 332):
    if T < T_melt:
        st = "固态(溴冰)"
    elif T > T_boil:
        st = "气态"
    else:
        st = f"液态, ρ={rho_Br2(T):.0f} kg/m^3"
    print(f"  T = {T:6.1f} K : {st}")

print()
print("=" * 74)
print("2) 液溴 vs 海水 密度 (分层判据)")
print("=" * 74)
print("  温度K  盐度   深度    液溴密度   海水密度   密度比   能否沉底")
for T in (273, 293, 300):
    for S, h in ((35, 1000), (35, 4000), (120, 4000)):
        rb = rho_Br2(T)
        rs = rho_sw(T, S, h)
        print(f"  {T:5.0f}  {S:5.0f}  {h:5d}m   {rb:8.0f}  {rs:8.0f}   {rb/rs:5.2f}   {'是' if rb>rs else '否'}")

print()
print("=" * 74)
print("3) 互溶性: 液溴在水中溶解度 ~32 g/L (20C), 超过即析出独立液相")
print("=" * 74)
sol = 32.0   # g/L
print(f"  饱和溶解度 ≈ {sol} g/L = {sol/3.102:.0f} mL 液溴 / L 水")
print("  密度比 3.0 倍, 析出的液溴相沉底 -> 形成清晰两相分层")

print()
print("=" * 74)
print("4) 来源: 需多少水柱的 Br- 才能形成厚度 d 的液溴层")
print("=" * 74)
print("   Br-浓度(mg/L)   1m厚液溴层所需水柱高度")
for C in (65, 650, 6500, 65000):     # 地球海水 Br- ≈ 65 mg/L
    H = 1.0 * rho_Br2(293) / (C / 1000.0)   # kg/m^3 / (kg/m^3) -> m
    print(f"   {C:8.0f}          {H/1000:8.1f} km")
print("   (地球海水 Br- ≈ 65 mg/L, 全球海水总量可支持的总液溴层极薄,")
print("    故自然分层必须依赖局部富集: 卤水/蒸发岩/热液)")

print()
print("=" * 74)
print("5) 温度窗口: 液溴层 与 液态CO2层 互斥")
print("=" * 74)
print("   液溴层  : 需 T > 265.8K 且 T < 332K  (暖海)")
print("   液态CO2层: 需 T < ~250K             (冷海)")
print("   => 二者温度窗口无交集, 同一海域不能同时存在")

print()
print("=" * 74)
print("6) 氧化来源可行性 (富氧行星)")
print("=" * 74)
print("   Br2 + 2e- -> 2Br-   E° = +1.07 V")
print("   O2 + 4H+ + 4e- -> 2H2O E° = +1.23 V")
print("   ΔE = 0.16 V > 0 -> O2 热力学上可氧化 Br- 为 Br2")
print("   但动力学极慢, 需生物催化(溴过氧化物酶类)或光催化")
print("   富氧行星(20% O2)为 Br- 氧化提供了热力学前提")

print()
print("== 结论 ==")
print("  1) 液溴分层的物理条件极好: 密度约海水的3倍(3.1 vs 1.03), 微溶, 沉底后两相界面清晰。")
print("  2) 温度窗口是硬约束: 需暖海(>265.8K), 与液态CO2层(冷海<250K)互斥;")
print("     极点海面240K下液溴直接凝固为固态溴, 无法成层。")
print("  3) 真正瓶颈是来源: 自然海水Br-仅65 mg/L, 形成1m厚液溴层需约48km水柱,")
print("     全球海水无法自然富集; 必须依赖局部卤水/蒸发岩/热液富集。")
print("  4) 富氧大气提供了Br-氧化的热力学前提, 但需生物或光催化提供动力学。")
print("  5) 生态: 液溴层是强氧化致死带, 可作极端生态位(溴呼吸生物), 但与常规定居生物不相容。")